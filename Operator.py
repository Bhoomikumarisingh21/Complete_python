#Arithmetic Operators
a = 20
b = 10

print("Addition =", a + b)
print("Subtraction =", a - b)
print("Multiplication =", a * b)
print("Division =", a / b)
print("Modulus =", a % b)

#Relational Operators
a = 10
b = 20

print(a > b)
print(a < b)
print(a == b)
print(a != b)

#Logical Operators
x = True
y = False

print(x and y)
print(x or y)
print(not x)

#Check Even or Odd
